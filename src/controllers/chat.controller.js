const requireRelationship = (req, res) => {
  if (!req.user.relationshipId) {
    res.status(400).json({ success: false, message: 'Not in a relationship' });
    return false;
  }
  return true;
};

const HEX_COLOR_RE = /^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/;

// Message bubble color is a per-user preference, shared with the partner in
// real time so both devices render this person's messages consistently.
exports.updateBubbleColor = async (req, res) => {
  if (!requireRelationship(req, res)) return;
  const color = typeof req.body.color === 'string' ? req.body.color.trim() : '';
  if (!HEX_COLOR_RE.test(color)) {
    return res.status(400).json({ success: false, message: 'Invalid color' });
  }

  await User.findByIdAndUpdate(req.user._id, { bubbleColor: color });

  const io = getIo();
  if (io) {
    io.to(`relationship:${req.user.relationshipId}`).emit('bubbleColor:updated', {
      userId: req.user._id,
      color,
    });
  }

  res.json({ success: true, data: { color } });
};

exports.getMessages = async (req, res) => {
  if (!requireRelationship(req, res)) return;
  const { page = 1, limit = 50, before, windowDays = 4 } = req.query;
  console.log(`[Chat] getMessages | user: ${req.user._id} | page: ${page} | limit: ${limit} | before: ${before || 'N/A'} | windowDays: ${before ? 'N/A' : windowDays}`);

  const baseQuery = { relationshipId: req.user.relationshipId, isDeleted: false };
  const query = { ...baseQuery };
  if (before) {
    // Paging further back through history — the age window below only applies
    // to the initial, most-recent load.
    query.createdAt = { $lt: new Date(before) };
  } else if (Number(windowDays) > 0) {
    query.createdAt = { $gte: new Date(Date.now() - Number(windowDays) * 24 * 60 * 60 * 1000) };
  }

  // Sorted by the SENDER's clock, falling back to server time for messages
  // predating clientSentAt. A batch flushed late would otherwise be appended to
  // the end of the thread instead of slotting back where it was typed.
  const fetchPage = q => Message.find(q)
    .populate('senderId', 'name nickname profilePhoto bubbleColor')
    .populate('replyTo')
    .sort({ clientSentAt: -1, createdAt: -1 })
    .skip((page - 1) * limit)
    .limit(Number(limit));

  let messages = await fetchPage(query);

  // A thread the couple hasn't touched in over `windowDays` must not look
  // empty on open — fall back to the most recent messages regardless of age.
  if (!before && messages.length === 0 && Number(page) === 1) {
    messages = await fetchPage(baseQuery);
  }

  const total = await Message.countDocuments(baseQuery);
  console.log(`[Chat] getMessages result | fetched: ${messages.length} | total: ${total}`);
  res.json({ success: true, data: { messages: messages.reverse(), total, page: Number(page) } });
};

// Shared by the REST sendMessage controller (text+media), the `message:send`
// socket handler (text, real-time path), and bulkSyncMessages (offline catch-up)
// so the LoveTree/XP/first-message side effects live in exactly one place.
const createAndPersistMessage = async (user, { content, type = 'text', mediaUrl = '', replyTo = null, isSecret = false, clientMessageId = null, clientSentAt = null }) => {
  const message = await Message.create({
    relationshipId: user.relationshipId,
    senderId: user._id,
    content: content || '',
    type,
    mediaUrl,
    replyTo: replyTo || null,
    isSecret,
    clientMessageId,
    clientSentAt: clientSentAt ? new Date(clientSentAt) : null,
  });

  await User.findByIdAndUpdate(user._id, {
    $push: {
      messages: {
        messageId: message._id,
        content: message.content,
        type: message.type,
        mediaUrl: message.mediaUrl,
        isSecret: message.isSecret,
        sentAt: message.createdAt,
        toRelationshipId: message.relationshipId,
      },
    },
  });

  const msgCount = await Message.countDocuments({ relationshipId: user.relationshipId });
  if (msgCount === 1) {
    await TimelineEvent.create({
      relationshipId: user.relationshipId,
      eventType: 'first_chat',
      title: 'First Message 💌',
      description: 'You sent your first message!',
      eventDate: new Date(),
      isAutoGenerated: true,
    });
  }

  // Point/XP values and daily caps live in constants/progression.js
  await awardTreePoints(user.relationshipId, 'message');
  awardXP(user.relationshipId, 'message');
  await message.populate('senderId', 'name nickname profilePhoto bubbleColor');
  return message;
};
exports.createAndPersistMessage = createAndPersistMessage;

exports.sendMessage = async (req, res) => {
  if (!requireRelationship(req, res)) return;
  const { content, type = 'text', replyTo, isSecret = false, clientMessageId, clientSentAt } = req.body;
  console.log(`[Chat] sendMessage | user: ${req.user._id} | type: ${type} | file: ${req.file ? req.file.mimetype : 'none'}`);

  if (!content && !req.file) {
    console.log(`[Chat] sendMessage failed | no content and no file`);
    return res.status(400).json({ success: false, message: 'Content or file required' });
  }

  // A retried upload must not create a second message. Returning the existing
  // one keeps the client's reconciliation identical to the first-try path.
  if (clientMessageId) {
    const existing = await Message.findOne({
      relationshipId: req.user.relationshipId,
      clientMessageId,
    }).populate('senderId', 'name nickname profilePhoto bubbleColor');
    if (existing) {
      console.log(`[Chat] sendMessage duplicate ${clientMessageId} — returning stored message`);
      return res.status(200).json({
        success: true,
        message: 'Message already sent',
        data: { messageId: existing._id, message: existing },
      });
    }
  }

  // Any upload is an image — the filter admits nothing else — so the type comes
  // from whether a file is present, not from the client's label.
  const resolvedType = req.file ? 'image' : type;

  const message = await createAndPersistMessage(req.user, {
    content,
    type: resolvedType,
    mediaUrl: req.file ? req.file.cloudUrl : '',
    replyTo,
    isSecret,
    clientMessageId: clientMessageId || null,
    clientSentAt: clientSentAt || new Date(),
  });
  console.log(`[Chat] Message saved to DB | messageId: ${message._id}`);

  const io = getIo();
  if (io) {
    const target = `user:${req.user.partnerId}`;
    console.log(`[Chat] Emitting message:new to ${target} | messageId: ${message._id}`);
    io.to(target).emit('message:new', message);
  } else {
    console.warn(`[Chat] Socket IO not available, message:new not emitted`);
  }

  console.log(`[Chat] sendMessage success | messageId: ${message._id}`);
  res.status(201).json({ success: true, message: 'Message sent', data: { messageId: message._id, message } });
};

const BULK_MAX = 100;

/**
 * The ONLY durable write path for chat.
 *
 * The socket delivers messages in real time but stores nothing, so every
 * message reaches the database through here, in batches the client flushes on a
 * size threshold or a timer. Three properties matter:
 *
 *   Idempotent — a batch that timed out client-side is retried verbatim, so the
 *     same clientMessageId will arrive again. One `bulkWrite` of upserts keyed
 *     on (relationshipId, clientMessageId) makes the replay a no-op instead of
 *     a duplicate, and the unique partial index enforces it even if two devices
 *     flush the same outbox concurrently.
 *
 *   Ordered — `clientSentAt` comes from the sending device, so a batch stored
 *     minutes late still sorts into its rightful place in the thread.
 *
 *   Partially failable — one bad item (bad type, missing id) must not cost the
 *     other 99 their persistence, so items are validated up front and only the
 *     rejects are reported back.
 *
 * The per-message side effects that used to live in createAndPersistMessage
 * (tree points, XP, the first-message timeline event) are applied ONCE for the
 * batch rather than per message — they were never meant to be a function of how
 * the client happens to chunk its outbox.
 */
exports.bulkSyncMessages = async (req, res) => {
  if (!requireRelationship(req, res)) return;
  const { messages } = req.body;
  if (!Array.isArray(messages) || messages.length === 0) {
    return res.status(400).json({ success: false, message: 'messages array required' });
  }
  if (messages.length > BULK_MAX) {
    return res.status(413).json({
      success: false,
      message: `Too many messages in one batch (max ${BULK_MAX})`,
    });
  }

  const relationshipId = req.user.relationshipId;
  const VALID_TYPES = ['text', 'voice', 'photo', 'note'];

  const rejected = [];
  const accepted = [];
  const seen = new Set();

  for (const item of messages) {
    const id = item?.clientMessageId;
    if (!id || typeof id !== 'string') {
      rejected.push({ clientMessageId: id ?? null, error: 'clientMessageId required' });
      continue;
    }
    // A batch that repeats an id within itself would make bulkWrite's upserts
    // race against each other on the unique index.
    if (seen.has(id)) continue;
    seen.add(id);

    const type = VALID_TYPES.includes(item.type) ? item.type : 'text';
    if (!item.content && !item.mediaUrl) {
      rejected.push({ clientMessageId: id, error: 'content or mediaUrl required' });
      continue;
    }
    accepted.push({
      clientMessageId: id,
      relationshipId,
      senderId: req.user._id,
      content: item.content || '',
      type,
      mediaUrl: item.mediaUrl || '',
      replyTo: item.replyTo || null,
      isSecret: !!item.isSecret,
      clientSentAt: item.clientSentAt ? new Date(item.clientSentAt) : new Date(),
      // Receipts the sender collected while the message was still queued.
      // Delivery is now something we learn from the recipient's device rather
      // than assume, so this defaults to false instead of the schema's legacy
      // `true` — otherwise every message would render two ticks on reload.
      isDelivered: !!item.delivered,
      isRead: !!item.read,
    });
  }

  if (!accepted.length) {
    return res.json({ success: true, data: { synced: [], rejected, syncedCount: 0 } });
  }

  // $setOnInsert only: a replayed batch must never overwrite a message the user
  // has since edited, reacted to, pinned or deleted.
  let written = [];
  try {
    await Message.bulkWrite(
      accepted.map((doc) => ({
        updateOne: {
          filter: { relationshipId, clientMessageId: doc.clientMessageId },
          update: { $setOnInsert: doc },
          upsert: true,
        },
      })),
      { ordered: false },
    );

    written = await Message.find({
      relationshipId,
      clientMessageId: { $in: accepted.map((d) => d.clientMessageId) },
    })
      .populate('senderId', 'name nickname profilePhoto bubbleColor')
      .populate('replyTo')
      .lean();
  } catch (err) {
    // A duplicate-key error here means a concurrent flush already stored those
    // ids — the desired end state either way, so re-read rather than fail.
    if (err.code !== 11000) {
      console.error('[Chat] bulkSyncMessages failed:', err.message);
      return res.status(500).json({ success: false, message: 'Could not sync messages' });
    }
    written = await Message.find({
      relationshipId,
      clientMessageId: { $in: accepted.map((d) => d.clientMessageId) },
    })
      .populate('senderId', 'name nickname profilePhoto bubbleColor')
      .populate('replyTo')
      .lean();
  }

  // Only ids that were genuinely new this call should earn progression.
  const freshCount = written.filter((m) => {
    const age = Date.now() - new Date(m.createdAt).getTime();
    return age < 60_000;
  }).length;

  if (freshCount > 0) {
    const total = await Message.countDocuments({ relationshipId });
    if (total === freshCount) {
      await TimelineEvent.create({
        relationshipId,
        eventType: 'first_chat',
        title: 'First Message 💌',
        description: 'You sent your first message!',
        eventDate: new Date(),
        isAutoGenerated: true,
      }).catch((err) => console.error('[Chat] first_chat timeline failed:', err.message));
    }
    // Awarded once per batch — the daily caps in constants/progression.js are
    // what actually bound this, not the message count.
    await awardTreePoints(relationshipId, 'message');
    awardXP(relationshipId, 'message');
  }

  // Tell the partner these are now durable, so their copy can drop the
  // "pending sync" marker the socket relay gave it.
  const io = getIo();
  if (io && req.user.partnerId) {
    io.to(`user:${req.user.partnerId}`).emit('message:synced', {
      relationshipId: String(relationshipId),
      messages: written,
    });
  }

  res.json({
    success: true,
    data: {
      synced: written.map((m) => ({ clientMessageId: m.clientMessageId, message: m })),
      rejected,
      syncedCount: written.length,
    },
  });
};

exports.deleteMessage = async (req, res) => {
  if (!requireRelationship(req, res)) return;
  const msg = await Message.findOne({ _id: req.params.id, relationshipId: req.user.relationshipId });
  if (!msg) return res.status(404).json({ success: false, message: 'Message not found' });
  if (msg.senderId.toString() !== req.user._id.toString()) {
    return res.status(403).json({ success: false, message: 'Cannot delete partner message' });
  }
  msg.isDeleted = true;
  await msg.save();
  res.json({ success: true, message: 'Message deleted' });
};

exports.editMessage = async (req, res) => {
  if (!requireRelationship(req, res)) return;
  const content = typeof req.body.content === 'string' ? req.body.content.trim() : '';
  if (!content) {
    return res.status(400).json({ success: false, message: 'Content required' });
  }

  const msg = await Message.findOne({ _id: req.params.id, relationshipId: req.user.relationshipId });
  if (!msg) return res.status(404).json({ success: false, message: 'Message not found' });
  if (msg.senderId.toString() !== req.user._id.toString()) {
    return res.status(403).json({ success: false, message: 'Cannot edit partner message' });
  }
  if (msg.type !== 'text') {
    return res.status(400).json({ success: false, message: 'Only text messages can be edited' });
  }

  msg.content = content;
  msg.isEdited = true;
  await msg.save();

  const io = getIo();
  if (io) {
    io.to(`relationship:${req.user.relationshipId}`).emit('message:edited', {
      messageId: msg._id,
      content: msg.content,
    });
  }

  res.json({ success: true, message: 'Message updated', data: { message: msg } });
};

exports.reactToMessage = async (req, res) => {
  if (!requireRelationship(req, res)) return;
  const { emoji } = req.body;
  if (!emoji) return res.status(400).json({ success: false, message: 'Emoji required' });

  const msg = await Message.findOne({ _id: req.params.id, relationshipId: req.user.relationshipId });
  if (!msg) return res.status(404).json({ success: false, message: 'Message not found' });

  const existing = msg.reactions.find(r => r.userId.toString() === req.user._id.toString());
  if (existing) existing.emoji = emoji;
  else msg.reactions.push({ userId: req.user._id, emoji });

  await msg.save();

  const io = getIo();
  if (io) {
    io.to(`relationship:${req.user.relationshipId}`).emit('message:reaction', { messageId: msg._id, reactions: msg.reactions });
  }

  res.json({ success: true, message: 'Reaction added', data: { reactions: msg.reactions } });
};

